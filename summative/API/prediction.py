"""
Rwanda crop price API.

Predicts the retail price (RWF per kg) of a crop in a Rwandan market for a given month,
so farmers can decide where and when to sell.

Routes
    POST /predict  - inputs -> predicted price
    POST /retrain  - upload a CSV of new price records -> model is retrained and used immediately
                     (defined in retrain.py)
    GET  /docs     - Swagger UI (generated by FastAPI)

Run locally:  uvicorn prediction:app --reload   (from the API folder)
"""

import difflib
import os
import threading
from pathlib import Path
import joblib
import pandas as pd
from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, ConfigDict, Field, ValidationInfo, field_validator
from retrain import FEATURES, FEATURES_CAT, router as retrain_router

BASE_DIR = Path(__file__).resolve().parent
MODEL_PATH = BASE_DIR / "best_model.pkl"
DATA_PATH = BASE_DIR / "training_data.csv"


# --------------------------------------------------------------------------------------
# Model state. Loaded from the repository at startup. /retrain swaps in a new model in memory.
# A retrained model lasts until the service restarts (Render's free plan restarts after sleeping);
# after that the model committed to the repo is loaded again.
# --------------------------------------------------------------------------------------
_lock = threading.Lock()
model = joblib.load(MODEL_PATH)
training_data = pd.read_csv(DATA_PATH)


def model_name(m) -> str:
    return type(m.regressor_.named_steps["model"]).__name__


def known_categories() -> dict[str, list[str]]:
    """Category values the current model was trained on, read from its one-hot encoder."""
    encoder = model.regressor_.named_steps["pre"].named_transformers_["cat"]
    return {col: list(cats) for col, cats in zip(FEATURES_CAT, encoder.categories_)}


def predict_price(row: dict) -> float:
    """Same function as in the notebook: predict RWF/kg for one input row."""
    return float(model.predict(pd.DataFrame([row])[FEATURES])[0])


# --------------------------------------------------------------------------------------
# App and CORS
# --------------------------------------------------------------------------------------
app = FastAPI(
    title="Rwanda Crop Price Prediction API",
    description=(
        "Predicts the retail price (RWF per kg) of a crop in a Rwandan market for a given month, "
        "using WFP market price data. Helps farmers decide where and when to sell."
    ),
    version="1.0.0",
)

# CORS decides which *websites* (browser origins) may call this API from JavaScript.
# It doesn't affect the Flutter mobile app, which isn't a browser, nor curl or Postman.
#
# ALLOWED:
#   - origins: only the deployed Render site (so Swagger UI's "Try it out" works) and the
#     local Flutter web debug server (started with --web-port 5000) for development.
#     No wildcard "*", so a random website can't use this API from its visitors' browsers.
#   - methods: GET (docs, health check) and POST (/predict, /retrain), which are the only
#     methods the API serves. PUT, DELETE and PATCH are refused.
#   - headers: Content-Type (needed to send JSON or a CSV upload) and Accept. Nothing else.
# RESTRICTED:
#   - credentials: False. The API uses no cookies or login sessions, so browsers aren't
#     allowed to send them. That removes the risk of another site making requests with a
#     user's credentials.
# Extra origins can be added without code changes via the ALLOWED_ORIGINS env var (comma-separated).
ALLOWED_ORIGINS = [
    "https://rwanda-crop-price-api-ryiy.onrender.com",
    "http://localhost:5000",
    "http://127.0.0.1:5000",
] + [o.strip() for o in os.getenv("ALLOWED_ORIGINS", "").split(",") if o.strip()]

app.add_middleware(
    CORSMiddleware,
    allow_origins=ALLOWED_ORIGINS,
    allow_methods=["GET", "POST"],
    allow_headers=["Content-Type", "Accept"],
    allow_credentials=False,
)


# --------------------------------------------------------------------------------------
# Request / response schemas
# --------------------------------------------------------------------------------------
class PriceRequest(BaseModel):
    """One prediction request. strict=True means "2024" (a string) is rejected for an int field."""

    model_config = ConfigDict(
        strict=True,
        json_schema_extra={"examples": [{
            "commodity": "Maize", "market": "Nyabugogo", "province": "Kigali City",
            "district": "Nyarugenge", "latitude": -1.95, "longitude": 30.06, "year": 2025, "month": 3,
        }]},
    )

    commodity: str = Field(min_length=2, max_length=60, description="Crop name as in WFP data, e.g. 'Maize'")
    market: str = Field(min_length=2, max_length=60, description="Market name, e.g. 'Nyabugogo'")
    province: str = Field(min_length=2, max_length=40, description="Province, e.g. 'Kigali City'")
    district: str = Field(min_length=2, max_length=40, description="District, e.g. 'Nyarugenge'")
    # Rwanda lies roughly between latitude -2.85 and -1.05, longitude 28.85 and 30.90.
    latitude: float = Field(ge=-2.9, le=-1.0, description="Market latitude (Rwanda: -2.9 to -1.0)")
    longitude: float = Field(ge=28.8, le=31.0, description="Market longitude (Rwanda: 28.8 to 31.0)")
    year: int = Field(ge=2000, le=2035, description="Year, 2000-2035")
    month: int = Field(ge=1, le=12, description="Month, 1-12")

    @field_validator("commodity", "market", "province", "district")
    @classmethod
    def must_be_known(cls, value: str, info: ValidationInfo) -> str:
        """Only accept names the model was trained on (case-insensitive) and suggest close matches."""
        options = known_categories()[info.field_name]
        lookup = {o.lower(): o for o in options}
        if value.strip().lower() in lookup:
            return lookup[value.strip().lower()]
        close = difflib.get_close_matches(value, options, n=3, cutoff=0.5)
        hint = f" Did you mean: {', '.join(close)}?" if close else f" {len(options)} values are accepted; see GET /options."
        raise ValueError(f"unknown {info.field_name} '{value}'.{hint}")


class PriceResponse(BaseModel):
    predicted_price_rwf_per_kg: float
    model: str
    inputs: PriceRequest


# --------------------------------------------------------------------------------------
# Routes
# --------------------------------------------------------------------------------------
@app.get("/", tags=["info"])
def root():
    return {"message": "Rwanda Crop Price Prediction API. Open /docs to try it.",
            "model": model_name(model), "training_rows": len(training_data)}


@app.get("/options", tags=["info"])
def options():
    """Accepted values for the text inputs (commodity, market, province, district)."""
    return known_categories()


@app.post("/predict", response_model=PriceResponse, tags=["prediction"])
def predict(req: PriceRequest):
    price = predict_price(req.model_dump())
    return PriceResponse(predicted_price_rwf_per_kg=round(price, 2), model=model_name(model), inputs=req)


# POST /retrain and GET /retrain/status live in retrain.py.
app.include_router(retrain_router)
